--  VISTAS

CREATE VIEW v_incidencia_detalle AS
SELECT
    i.id,
    i.codigo,
    i.descripcion,
    c.nombre                         AS categoria,
    e.codigo                         AS espacio_codigo,
    e.nombre                         AS espacio,
    ed.nombre                        AS edificio,
    e.planta,
    i.prioridad,
    p.orden                          AS prioridad_orden,
    i.estado,
    i.riesgo_personas,
    i.impide_uso,
    i.foto_ruta,
    i.creada_por                     AS creada_por_id,
    uc.nombre || ' ' || uc.apellidos AS creada_por,
    ut.nombre || ' ' || ut.apellidos AS tecnico,
    pr.razon_social                  AS proveedor,
    COALESCE(ut.nombre || ' ' || ut.apellidos, pr.razon_social, 'Sin asignar') AS asignada_a,
    i.fecha_creacion,
    i.fecha_objetivo,
    i.fecha_resolucion,
    i.fecha_cierre,
    CASE
        WHEN i.fecha_resolucion IS NULL THEN i.fecha_objetivo < CURRENT_DATE
        ELSE i.fecha_resolucion::date > i.fecha_objetivo
    END                              AS fuera_de_plazo
FROM incidencia i
JOIN categoria  c   ON c.id  = i.categoria_id
JOIN espacio    e   ON e.id  = i.espacio_id
JOIN edificio   ed  ON ed.id = e.edificio_id
JOIN prioridad  p   ON p.codigo = i.prioridad
JOIN usuario    uc  ON uc.id = i.creada_por
LEFT JOIN usuario   ut ON ut.id = i.tecnico_id
LEFT JOIN proveedor pr ON pr.id = i.proveedor_id;

-- Panel resumen: número de incidencias por estado.
CREATE VIEW v_resumen_estado AS
SELECT ei.codigo AS estado, ei.orden, COUNT(i.id) AS total
FROM estado_incidencia ei
LEFT JOIN incidencia i ON i.estado = ei.codigo
GROUP BY ei.codigo, ei.orden;

-- Panel resumen: número de incidencias por prioridad.
CREATE VIEW v_resumen_prioridad AS
SELECT p.codigo AS prioridad, p.orden, COUNT(i.id) AS total
FROM prioridad p
LEFT JOIN incidencia i ON i.prioridad = p.codigo
GROUP BY p.codigo, p.orden;

-- Informe de salida: incidencias sin resolver cuya fecha objetivo ya paso.
CREATE VIEW v_incidencias_fuera_plazo AS
SELECT
    d.codigo, d.espacio_codigo, d.espacio, d.categoria, d.prioridad, d.prioridad_orden,
    d.estado, d.asignada_a, d.fecha_creacion, d.fecha_objetivo,
    CURRENT_DATE - d.fecha_objetivo AS dias_de_retraso
FROM v_incidencia_detalle d
WHERE d.estado IN ('ABIERTA', 'EN_CURSO')
  AND d.fecha_objetivo < CURRENT_DATE;


--  TRIGGERS: reglas de negocio y auditoria


--  Usuario de la aplicacion que hace la operacion (o NULL)

CREATE FUNCTION fixit_usuario_actual() RETURNS INTEGER
LANGUAGE sql STABLE AS $$
    SELECT NULLIF(current_setting('fixit.usuario_id', true), '')::INTEGER
$$;



--  Antes de insertar o modificar una incidencia: validaciones

CREATE FUNCTION fn_incidencia_validar() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    v_rol             VARCHAR(10);
    v_comprobar_rol   BOOLEAN := FALSE;
    v_orden_anterior  SMALLINT;
    v_orden_nuevo     SMALLINT;
BEGIN
    IF NEW.tecnico_id IS NOT NULL THEN
        IF TG_OP = 'INSERT' THEN
            v_comprobar_rol := TRUE;
        ELSE
            v_comprobar_rol := NEW.tecnico_id IS DISTINCT FROM OLD.tecnico_id;
        END IF;
    END IF;

    IF v_comprobar_rol THEN
        SELECT rol INTO v_rol FROM usuario WHERE id = NEW.tecnico_id;
        IF v_rol IS NOT NULL AND v_rol <> 'TECNICO' THEN
            RAISE EXCEPTION 'FIXIT: el usuario % no tiene el rol TECNICO', NEW.tecnico_id
                USING HINT = 'Solo se puede asignar a usuarios con rol TECNICO o a un proveedor.';
        END IF;
    END IF;

    IF TG_OP = 'UPDATE' AND NEW.estado <> OLD.estado THEN
        SELECT orden INTO v_orden_anterior FROM estado_incidencia WHERE codigo = OLD.estado;
        SELECT orden INTO v_orden_nuevo    FROM estado_incidencia WHERE codigo = NEW.estado;

        IF v_orden_nuevo IS NULL OR v_orden_nuevo <> v_orden_anterior + 1 THEN
            RAISE EXCEPTION 'FIXIT: cambio de estado no permitido (% -> %) en %',
                            OLD.estado, NEW.estado, OLD.codigo
                USING HINT = 'El ciclo es ABIERTA > EN_CURSO > RESUELTA > CERRADA.';
        END IF;

        IF NEW.estado = 'RESUELTA' AND NEW.fecha_resolucion IS NULL THEN
            NEW.fecha_resolucion := LOCALTIMESTAMP(0);
        END IF;
        IF NEW.estado = 'CERRADA' AND NEW.fecha_cierre IS NULL THEN
            NEW.fecha_cierre := LOCALTIMESTAMP(0);
        END IF;
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_incidencia_validar
    BEFORE INSERT OR UPDATE ON incidencia
    FOR EACH ROW EXECUTE FUNCTION fn_incidencia_validar();



--  Despues de insertar, modificar o borrar una incidencia: auditoria

CREATE FUNCTION fn_incidencia_auditar() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    v_cambios VARCHAR(400) := '';
BEGIN
    IF TG_OP = 'INSERT' THEN
        INSERT INTO log_operacion (origen, operacion, tabla, registro_id, usuario_id, mensaje)
        VALUES ('TRIGGER', 'INSERT', 'incidencia', NEW.id, fixit_usuario_actual(),
                'Alta de ' || NEW.codigo || ' con estado ' || NEW.estado
                || ' y prioridad ' || NEW.prioridad);

    ELSIF TG_OP = 'UPDATE' THEN
        IF NEW.estado <> OLD.estado THEN
            v_cambios := v_cambios || ' estado ' || OLD.estado || ' -> ' || NEW.estado || ';';
        END IF;
        IF NEW.prioridad <> OLD.prioridad THEN
            v_cambios := v_cambios || ' prioridad ' || OLD.prioridad || ' -> ' || NEW.prioridad || ';';
        END IF;
        IF NEW.tecnico_id IS DISTINCT FROM OLD.tecnico_id THEN
            v_cambios := v_cambios || ' tecnico ' || COALESCE(OLD.tecnico_id::TEXT, 'ninguno')
                         || ' -> ' || COALESCE(NEW.tecnico_id::TEXT, 'ninguno') || ';';
        END IF;
        IF NEW.proveedor_id IS DISTINCT FROM OLD.proveedor_id THEN
            v_cambios := v_cambios || ' proveedor ' || COALESCE(OLD.proveedor_id::TEXT, 'ninguno')
                         || ' -> ' || COALESCE(NEW.proveedor_id::TEXT, 'ninguno') || ';';
        END IF;
        IF v_cambios = '' THEN
            v_cambios := ' otros datos;';
        END IF;

        INSERT INTO log_operacion (origen, operacion, tabla, registro_id, usuario_id, mensaje)
        VALUES ('TRIGGER', 'UPDATE', 'incidencia', NEW.id, fixit_usuario_actual(),
                'Cambio en ' || NEW.codigo || ':' || v_cambios);

    ELSE  -- DELETE: no debería ser habitual, se marca como WARN
        INSERT INTO log_operacion (nivel, origen, operacion, tabla, registro_id, usuario_id, mensaje)
        VALUES ('WARN', 'TRIGGER', 'DELETE', 'incidencia', OLD.id, fixit_usuario_actual(),
                'Borrado de ' || OLD.codigo || ' (estado ' || OLD.estado || ')');
    END IF;

    RETURN NULL; 
END;
$$;

CREATE TRIGGER trg_incidencia_auditar
    AFTER INSERT OR UPDATE OR DELETE ON incidencia
    FOR EACH ROW EXECUTE FUNCTION fn_incidencia_auditar();



--  Despues de insertar un comentario: auditoria
CREATE FUNCTION fn_comentario_auditar() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    INSERT INTO log_operacion (origen, operacion, tabla, registro_id, usuario_id, mensaje)
    VALUES ('TRIGGER', 'INSERT', 'comentario', NEW.id, NEW.autor_id,
            'Nuevo comentario en la incidencia con id ' || NEW.incidencia_id);
    RETURN NULL;
END;
$$;

CREATE TRIGGER trg_comentario_auditar
    AFTER INSERT ON comentario
    FOR EACH ROW EXECUTE FUNCTION fn_comentario_auditar();
