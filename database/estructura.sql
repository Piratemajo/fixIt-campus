-- CATÁLOGOS

CREATE TABLE rol (
    codigo       VARCHAR(10)  NOT NULL,
    descripcion  VARCHAR(120) NOT NULL,
    CONSTRAINT pk_rol PRIMARY KEY (codigo)
);


CREATE TABLE prioridad (
    codigo                 VARCHAR(10)  NOT NULL,
    orden                  SMALLINT     NOT NULL,   
    plazo_dias_laborables  SMALLINT     NOT NULL,   
    descripcion            VARCHAR(120) NOT NULL,
    CONSTRAINT pk_prioridad PRIMARY KEY (codigo),
    CONSTRAINT uq_prioridad_orden UNIQUE (orden),
    CONSTRAINT chk_prioridad_orden CHECK (orden > 0),
    CONSTRAINT chk_prioridad_plazo CHECK (plazo_dias_laborables >= 0)
);


CREATE TABLE estado_incidencia (
    codigo       VARCHAR(10)  NOT NULL,
    orden        SMALLINT     NOT NULL,
    descripcion  VARCHAR(120) NOT NULL,
    CONSTRAINT pk_estado_incidencia PRIMARY KEY (codigo),
    CONSTRAINT uq_estado_orden UNIQUE (orden),
    CONSTRAINT chk_estado_orden CHECK (orden > 0)
);


CREATE TABLE categoria (
    id      SMALLINT    GENERATED BY DEFAULT AS IDENTITY,
    nombre  VARCHAR(40) NOT NULL,
    activa  BOOLEAN     NOT NULL DEFAULT TRUE,
    CONSTRAINT pk_categoria PRIMARY KEY (id),
    CONSTRAINT uq_categoria_nombre UNIQUE (nombre)
);



--  USUARIOS

CREATE TABLE usuario (
    id             INTEGER      GENERATED BY DEFAULT AS IDENTITY,
    nombre         VARCHAR(60)  NOT NULL,
    apellidos      VARCHAR(100) NOT NULL,
    email          VARCHAR(120) NOT NULL,
    password_hash  VARCHAR(100) NOT NULL,   
    rol            VARCHAR(10)  NOT NULL,
    activo         BOOLEAN      NOT NULL DEFAULT TRUE,
    fecha_alta     TIMESTAMP(0) NOT NULL DEFAULT LOCALTIMESTAMP(0),
    CONSTRAINT pk_usuario PRIMARY KEY (id),
    CONSTRAINT uq_usuario_email UNIQUE (email),
    CONSTRAINT fk_usuario_rol FOREIGN KEY (rol) REFERENCES rol (codigo),
    CONSTRAINT chk_usuario_email CHECK (email LIKE '_%@_%._%'),
    CONSTRAINT chk_usuario_nombre CHECK (CHAR_LENGTH(TRIM(nombre)) > 0)
);



--  ESPACIOS DEL CAMPUS

CREATE TABLE edificio (
    id      SMALLINT    GENERATED BY DEFAULT AS IDENTITY,
    codigo  VARCHAR(5)  NOT NULL,     -- 'A', 'B'...
    nombre  VARCHAR(80) NOT NULL,
    CONSTRAINT pk_edificio PRIMARY KEY (id),
    CONSTRAINT uq_edificio_codigo UNIQUE (codigo)
);

CREATE TABLE espacio (
    id           INTEGER     GENERATED BY DEFAULT AS IDENTITY,
    codigo       VARCHAR(10) NOT NULL,   -- 'B-12': identificador visible y clave de importación
    nombre       VARCHAR(80) NOT NULL,
    edificio_id  SMALLINT    NOT NULL,
    planta       SMALLINT    NOT NULL,   -- 0 = planta baja, negativos = sótanos
    tipo         VARCHAR(12) NOT NULL,
    activo       BOOLEAN     NOT NULL DEFAULT TRUE,  -- los espacios se desactivan, no se borran
    CONSTRAINT pk_espacio PRIMARY KEY (id),
    CONSTRAINT uq_espacio_codigo UNIQUE (codigo),
    CONSTRAINT uq_espacio_nombre_edificio UNIQUE (edificio_id, nombre),
    CONSTRAINT fk_espacio_edificio FOREIGN KEY (edificio_id) REFERENCES edificio (id),
    CONSTRAINT chk_espacio_planta CHECK (planta BETWEEN -2 AND 10),
    -- VARCHAR + CHECK en lugar de un tipo ENUM: se mapea sin trucos en JPA (2T).
    CONSTRAINT chk_espacio_tipo CHECK (tipo IN ('AULA', 'LABORATORIO', 'TALLER', 'ASEO', 'ZONA_COMUN'))
);



--  PROVEEDORES DE MANTENIMIENTO

CREATE TABLE proveedor (
    id               INTEGER      GENERATED BY DEFAULT AS IDENTITY,
    razon_social     VARCHAR(120) NOT NULL,
    nif              VARCHAR(9)   NOT NULL,   
    especialidad_id  SMALLINT     NOT NULL,   
    email_contacto   VARCHAR(120) NOT NULL,
    telefono         VARCHAR(15)  NULL,
    precio_hora      NUMERIC(6,2) NOT NULL, 
    activo           BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT pk_proveedor PRIMARY KEY (id),
    CONSTRAINT uq_proveedor_nif UNIQUE (nif),
    CONSTRAINT fk_proveedor_especialidad FOREIGN KEY (especialidad_id) REFERENCES categoria (id),
    CONSTRAINT chk_proveedor_precio CHECK (precio_hora > 0),
    CONSTRAINT chk_proveedor_nif CHECK (CHAR_LENGTH(nif) = 9)
);


--  INCIDENCIAS

CREATE TABLE incidencia (
    id                INTEGER       GENERATED BY DEFAULT AS IDENTITY,
    codigo            VARCHAR(12)   NOT NULL,   
    descripcion       VARCHAR(1000) NOT NULL,
    categoria_id      SMALLINT      NOT NULL,
    espacio_id        INTEGER       NOT NULL,
    riesgo_personas   BOOLEAN       NOT NULL DEFAULT FALSE,  
    impide_uso        BOOLEAN       NOT NULL DEFAULT FALSE,  
    prioridad         VARCHAR(10)   NOT NULL,
    estado            VARCHAR(10)   NOT NULL DEFAULT 'ABIERTA',
    foto_ruta         VARCHAR(255)  NULL,      
    creada_por        INTEGER       NOT NULL,
    tecnico_id        INTEGER       NULL,       
    proveedor_id      INTEGER       NULL,      
    fecha_creacion    TIMESTAMP(0)  NOT NULL DEFAULT LOCALTIMESTAMP(0),
    fecha_objetivo    DATE          NOT NULL,
    fecha_resolucion  TIMESTAMP(0)  NULL,
    fecha_cierre      TIMESTAMP(0)  NULL,
    version           INTEGER       NOT NULL DEFAULT 0, 

    CONSTRAINT pk_incidencia PRIMARY KEY (id),
    CONSTRAINT uq_incidencia_codigo UNIQUE (codigo),

    CONSTRAINT fk_incidencia_categoria  FOREIGN KEY (categoria_id) REFERENCES categoria (id),
    CONSTRAINT fk_incidencia_espacio    FOREIGN KEY (espacio_id)   REFERENCES espacio (id),
    CONSTRAINT fk_incidencia_prioridad  FOREIGN KEY (prioridad)    REFERENCES prioridad (codigo),
    CONSTRAINT fk_incidencia_estado     FOREIGN KEY (estado)       REFERENCES estado_incidencia (codigo),
    CONSTRAINT fk_incidencia_creador    FOREIGN KEY (creada_por)   REFERENCES usuario (id),
    CONSTRAINT fk_incidencia_tecnico    FOREIGN KEY (tecnico_id)   REFERENCES usuario (id),
    CONSTRAINT fk_incidencia_proveedor  FOREIGN KEY (proveedor_id) REFERENCES proveedor (id),

    CONSTRAINT chk_inc_descripcion
        CHECK (CHAR_LENGTH(TRIM(descripcion)) > 0),
    CONSTRAINT chk_inc_asignacion_unica
        CHECK (tecnico_id IS NULL OR proveedor_id IS NULL),

    CONSTRAINT chk_inc_riesgo_es_urgente
        CHECK (NOT riesgo_personas
               OR (prioridad = 'URGENTE' AND fecha_objetivo = fecha_creacion::date)),
    CONSTRAINT chk_inc_asignada_para_avanzar
        CHECK (estado = 'ABIERTA' OR tecnico_id IS NOT NULL OR proveedor_id IS NOT NULL),
    CONSTRAINT chk_inc_fecha_objetivo
        CHECK (fecha_objetivo >= fecha_creacion::date),
    CONSTRAINT chk_inc_fecha_resolucion
        CHECK ((estado IN ('RESUELTA', 'CERRADA')) = (fecha_resolucion IS NOT NULL)),
    CONSTRAINT chk_inc_fecha_cierre
        CHECK ((estado = 'CERRADA') = (fecha_cierre IS NOT NULL)),
    CONSTRAINT chk_inc_orden_fechas
        CHECK ((fecha_resolucion IS NULL OR fecha_resolucion >= fecha_creacion)
           AND (fecha_cierre IS NULL OR fecha_cierre >= fecha_resolucion))
);

